"""Build the Windows release: ``python packaging/build.py [--expect-tag vX.Y.Z]``.

1. render the app icon to ``build/opendrs.ico`` and write the .exe version resource;
2. run PyInstaller with ``packaging/opendrs.spec`` (one folder, windowed);
3. check the Qt files the app needs are present, then run the frozen ``OpenDRS.exe --self-test``
   on the offscreen and on the real Windows platform plugin; fail unless every check passed;
4. add the third-party licences, zip ``dist/OpenDRS`` to ``dist/OpenDRS-<version>-win64.zip`` (+ ``.sha256``).

Used unchanged by the GitHub Actions workflow, so a local build matches a release build.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import struct
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
DIST = ROOT / "dist"
NAME = "OpenDRS"
ICON_SIZES = (16, 24, 32, 48, 64, 128, 256)
SELF_TEST_TIMEOUT_S = 180
SELF_TEST_PLATFORMS = ("offscreen", "windows")
# Loaded at run time, so a dependency scan cannot vouch for them; the spec's filters must keep them.
REQUIRED_FILES = (
    "PySide6/plugins/platforms/qwindows.dll",
    "PySide6/plugins/platforms/qoffscreen.dll",
    "PySide6/plugins/styles/qmodernwindowsstyle.dll",
    "PySide6/plugins/iconengines/qsvgicon.dll",
    "PySide6/plugins/imageformats/qsvg.dll",
    "PySide6/translations/qtbase_zh_TW.qm",
)
ZH_TW_UNICODE = "040404B0"  # zh-TW, UTF-16 string table


def read_version() -> str:
    text = (ROOT / "src" / "opendrs" / "__init__.py").read_text(encoding="utf-8")
    match = re.search(r'^__version__ = "([^"]+)"', text, re.MULTILINE)
    if not match:
        raise SystemExit("找不到 src/opendrs/__init__.py 的 __version__")
    return match.group(1)


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """The leading dotted numbers as the 4 fields Windows wants ("1.2.3rc1" -> (1, 2, 3, 0))."""
    match = re.match(r"\d+(?:\.\d+){0,3}", version)
    if not match:
        raise SystemExit(f"版本號 {version!r} 不是以數字開頭")
    numbers = [int(n) for n in match.group(0).split(".")]
    return tuple(numbers + [0] * (4 - len(numbers)))  # type: ignore[return-value]


def ico_bytes(pngs: dict[int, bytes]) -> bytes:
    """A multi-size .ico whose entries are PNG images (supported since Windows Vista)."""
    header = struct.pack("<HHH", 0, 1, len(pngs))
    offset = len(header) + 16 * len(pngs)
    entries, data = b"", b""
    for size, png in sorted(pngs.items()):
        side = 0 if size >= 256 else size  # 0 means 256
        entries += struct.pack("<BBBBHHII", side, side, 0, 0, 1, 32, len(png), offset + len(data))
        data += png
    return header + entries + data


def render_icon(path: Path) -> None:
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    sys.path.insert(0, str(ROOT / "src"))
    from PySide6.QtCore import QBuffer, QByteArray, QIODevice, QSize
    from PySide6.QtWidgets import QApplication

    from opendrs.gui.theme import app_icon

    app = QApplication.instance() or QApplication([])  # noqa: F841 - QPixmap needs it
    icon = app_icon()
    pngs = {}
    for size in ICON_SIZES:
        raw = QByteArray()
        buffer = QBuffer(raw)
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        icon.pixmap(QSize(size, size)).toImage().save(buffer, "PNG")
        pngs[size] = bytes(raw.data())
    path.write_bytes(ico_bytes(pngs))


def version_info(version: str) -> str:
    """PyInstaller's version-resource file (shown in Explorer › Properties › Details)."""
    numbers = version_tuple(version)
    strings = {
        "CompanyName": "windasd",
        "FileDescription": "OpenDRS對講機寫頻軟體",
        "FileVersion": version,
        "InternalName": NAME,
        "LegalCopyright": "© windasd",
        "Comments": "https://github.com/windasd/OpenDRS",
        "OriginalFilename": f"{NAME}.exe",
        "ProductName": "OpenDRS",
        "ProductVersion": version,
    }
    table = ",\n          ".join(f"StringStruct({k!r}, {v!r})" for k, v in strings.items())
    return f"""# Generated by packaging/build.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers={numbers}, prodvers={numbers}, mask=0x3F, flags=0x0,
                    OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([
      StringTable({ZH_TW_UNICODE!r}, [
          {table}])]),
    VarFileInfo([VarStruct('Translation', [0x0404, 1200])])
  ]
)
"""


def run_pyinstaller() -> Path:
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                    "--distpath", str(DIST), "--workpath", str(BUILD / "pyinstaller"),
                    str(ROOT / "packaging" / "opendrs.spec")], check=True, cwd=ROOT)
    exe = DIST / NAME / f"{NAME}.exe"
    if not exe.is_file():
        raise SystemExit(f"PyInstaller 沒有產生 {exe}")
    return exe


def check_required_files(exe: Path) -> None:
    internal = exe.parent / "_internal"
    missing = [name for name in REQUIRED_FILES if not (internal / name).is_file()]
    if missing:
        raise SystemExit("打包結果缺少必要的 Qt 檔案（檢查 opendrs.spec 的排除清單）：" + "、".join(missing))


def self_test(exe: Path, version: str, platform: str) -> dict:
    report = BUILD / f"selftest_{platform}.json"
    report.unlink(missing_ok=True)
    env = dict(os.environ, QT_QPA_PLATFORM=platform)
    try:
        proc = subprocess.run([str(exe), "--self-test", str(report)], env=env,
                              timeout=SELF_TEST_TIMEOUT_S, check=False)
    except subprocess.TimeoutExpired as exc:
        raise SystemExit(f"自我測試（{platform}）超過 {SELF_TEST_TIMEOUT_S} 秒沒有結束") from exc
    if not report.is_file():
        raise SystemExit(f"自我測試（{platform}）沒有產生報告（結束碼 {proc.returncode}）")
    result = json.loads(report.read_text(encoding="utf-8"))
    print(f"--- self-test ({platform})")
    print(json.dumps(result, ensure_ascii=False, indent=2))
    if (proc.returncode != 0 or not result["ok"] or not result["frozen"] or result["version"] != version
            or result["checks"]["qt"] != f"ok: platform {platform}"):
        raise SystemExit(f"打包後的程式自我測試（{platform}）失敗")
    return result


def add_licenses(folder: Path) -> None:
    """Licence texts for everything bundled (see packaging/licenses/THIRD_PARTY_NOTICES.md)."""
    folder.mkdir(exist_ok=True)
    for src in (ROOT / "packaging" / "licenses").iterdir():
        shutil.copy2(src, folder / src.name)
    shutil.copy2(Path(sys.base_prefix) / "LICENSE.txt", folder / "Python-LICENSE.txt")
    copying = metadata.distribution("pyinstaller").locate_file(
        next(f for f in metadata.distribution("pyinstaller").files if f.name == "COPYING.txt"))
    shutil.copy2(Path(copying), folder / "PyInstaller-COPYING.txt")


def package(version: str) -> Path:
    shutil.copy2(ROOT / "README.md", DIST / NAME / "README.md")
    add_licenses(DIST / NAME / "licenses")
    archive = Path(shutil.make_archive(str(DIST / f"{NAME}-{version}-win64"), "zip", DIST, NAME))
    digest = write_checksum(archive)
    print(f"{archive}  {archive.stat().st_size / 1e6:.1f} MB  sha256 {digest}")
    return archive


def write_checksum(archive: Path) -> str:
    """``<archive>.sha256`` in `sha256sum -c` format; bytes, so Windows does not add a CR."""
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    archive.with_name(archive.name + ".sha256").write_bytes(f"{digest}  {archive.name}\n".encode("ascii"))
    return digest


def main() -> int:
    for stream in (sys.stdout, sys.stderr):  # CI consoles are cp1252: Chinese would raise
        if stream is not None and hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--expect-tag", help="release tag; must equal 'v' + the package version")
    args = parser.parse_args()
    version = read_version()
    if args.expect_tag and args.expect_tag != f"v{version}":
        raise SystemExit(f"標籤 {args.expect_tag} 與程式版本 {version} 不符（請先修改 src/opendrs/__init__.py "
                         "與 pyproject.toml 的版本）")
    BUILD.mkdir(exist_ok=True)
    for old in DIST.glob(f"{NAME}-*-win64.zip*"):
        old.unlink()
    render_icon(BUILD / "opendrs.ico")
    (BUILD / "version_info.txt").write_text(version_info(version), encoding="utf-8")
    exe = run_pyinstaller()
    check_required_files(exe)
    for platform in SELF_TEST_PLATFORMS:
        self_test(exe, version, platform)
    package(version)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
