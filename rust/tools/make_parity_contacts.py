def blob(data: bytes) -> str | dict:
    """Bytes for the oracle: hex, the generated BIG_BODY, or a long run of one byte compressed."""
    if data == BIG_BODY:
        return {"big_body": BIG_ROWS}
    runs = [(m.start(), m.end()) for m in re.finditer(rb"(.)\1{1023,}", data, re.S)]
    if not runs:
        return data.hex()
    start, end = max(runs, key=lambda r: r[1] - r[0])
    return {"prefix": data[:start].hex(), "byte": data[start], "count": end - start,
            "suffix": data[end:].hex()}


def ok_headers(body: bytes) -> list[list[str]]:
    return [["Content-Length", str(len(body))], ["Last-Modified", LAST_MODIFIED]]


