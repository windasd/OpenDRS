def run_download(scenario: dict) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        directory = Path(tmp) / "cache"
        if scenario.get("prepare"):
            radioid.download(directory, opener=lambda r, timeout: FakeResponse(
                TEST_CSV, dict(ok_headers(TEST_CSV))))
        if "meta" in scenario:
            (directory / "meta.json").write_bytes(scenario["meta"])
        seen: list = []
        progress: list = []

        def opener(request, timeout):  # noqa: ANN001, ANN202
            seen.append(request)
            if scenario.get("status"):
                raise HTTPError(request.full_url, scenario["status"], "x", {}, None)
            if scenario.get("connect"):
                raise URLError(scenario["connect"].removeprefix("<urlopen error ").removesuffix(">"))
            return FakeResponse(scenario["body"], dict(scenario["headers"]))

        saved = radioid.MAX_DOWNLOAD
        radioid.MAX_DOWNLOAD = scenario.get("max") or saved
        out: dict = {"result": None, "error": None}
        try:
            out["result"] = radioid.download(directory, progress=lambda g, t: progress.append([g, t]),
                                             opener=opener)
        except (RadioIdError, ValueError) as exc:
            out["error"] = str(exc)
        finally:
            radioid.MAX_DOWNLOAD = saved
        request = seen[0]
        csv_path, meta_path = directory / "user.csv", directory / "meta.json"
        meta = meta_path.read_bytes().decode() if meta_path.is_file() else None
        if meta is not None and '"downloaded_at"' in meta:
            meta = "\n".join(
                '  "downloaded_at": 0,' if ln.startswith('  "downloaded_at"') else ln
                for ln in meta.replace("\r\n", "\n").split("\n"))
        out.update({
            "user_agent": request.get_header("User-agent"),
            "if_modified_since": request.get_header("If-modified-since"),
            "progress": progress,
            "csv_sha256": sha(csv_path.read_bytes()) if csv_path.is_file() else None,
            "part_files": len(list(directory.glob("*.part"))),
            "meta": meta,
        })
        return out


