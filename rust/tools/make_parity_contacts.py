def ranges(code_points: list[int]) -> list[list[int]]:
    out: list[list[int]] = []
    for cp in code_points:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def unicode_facts() -> dict:
    chars = [chr(cp) for cp in range(MAX_CP)]
    return {
        "python": sys.version.split()[0],
        "unicode": unicodedata.unidata_version,
        "space": ranges([ord(c) for c in chars if c.isspace()]),
        "nonprintable": ranges([ord(c) for c in chars if not c.isprintable()]),
        "format": ranges([ord(c) for c in chars if unicodedata.category(c) == "Cf"]),
        "decimal": ranges([ord(c) for c in chars if unicodedata.decimal(c, None) is not None]),
        "casefold": [[ord(c), c.casefold()] for c in chars if c.casefold() != c],
    }


def casefold_runs(mapping: list[list]) -> tuple[list[tuple[int, int, int, int]], list[tuple[int, str]]]:
    """1:1 mappings as disjoint (first, last, stride, delta) runs; the rest one by one."""
    mapped = {cp for cp, _ in mapping}
    single = {cp: ord(to) - cp for cp, to in mapping if len(to) == 1}
    multi = [(cp, to) for cp, to in mapping if len(to) > 1]
    runs: list[tuple[int, int, int, int]] = []
    for cp in sorted(single):
        delta = single[cp]
        if runs and runs[-1][3] == delta:
            first, last, stride, _ = runs[-1]
            one_point = first == last
            if cp == last + 1 and (one_point or stride == 1):
                runs[-1] = (first, cp, 1, delta)
                continue
            # A stride-2 run never spans a mapped code point, so the runs stay disjoint.
            if cp == last + 2 and last + 1 not in mapped and (one_point or stride == 2):
                runs[-1] = (first, cp, 2, delta)
                continue
        runs.append((cp, cp, 1, delta))
    return runs, multi


def rust_pairs(name: str, doc: str, pairs: list[list[int]]) -> str:
    body = "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in pairs)
    return f"/// {doc}\npub(crate) const {name}: &[(u32, u32)] = &[\n{body}];\n"


def rust_string(text: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in text) + '"'


def rust_tables() -> str:
    facts = unicode_facts()
    runs, multi = casefold_runs(facts["casefold"])
    run_body = "".join(f"    (0x{a:x}, 0x{b:x}, {s}, {d}),\n" for a, b, s, d in runs)
    multi_body = "".join(f"    (0x{cp:x}, {rust_string(to)}),\n" for cp, to in multi)
    return "".join([
        f"//! Unicode tables of Python {facts['python']} (Unicode {facts['unicode']}), generated by\n",
        "//! `rust/tools/make_parity_contacts.py --tables`. Do not edit; regenerate instead.\n\n",
        rust_pairs("SPACE", "`str.isspace()`.", facts["space"]),
        "\n",
        rust_pairs("NONPRINTABLE", "Not `str.isprintable()`.", facts["nonprintable"]),
        "\n",
        rust_pairs("FORMAT", "General category Cf.", facts["format"]),
        "\n",
        rust_pairs("DECIMAL", "Decimal digits (`unicodedata.decimal`), in runs that start at 0.",
                   facts["decimal"]),
        "\n",
        "/// `str.casefold()` mappings to one character: (first, last, stride, delta).\n",
        f"pub(crate) const CASEFOLD_RUNS: &[(u32, u32, u32, i32)] = &[\n{run_body}];\n\n",
        "/// `str.casefold()` mappings to several characters.\n",
        f"pub(crate) const CASEFOLD_MULTI: &[(u32, &str)] = &[\n{multi_body}];\n",
    ])


