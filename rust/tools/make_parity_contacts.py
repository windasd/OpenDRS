def report_facts(report) -> dict:  # noqa: ANN001
    return {"added": report.added, "updated": report.updated, "unchanged": report.unchanged,
            "over_capacity": report.over_capacity, "kept": report.kept,
            "shortened": [list(s) for s in report.shortened], "summary": report.summary()}


def fixture_users(project: Project) -> list[RadioIdUser]:
    private = [c for c in project.contacts if c.kind == Contact.PRIVATE_CALL]
