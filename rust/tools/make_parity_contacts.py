def contacts_csv_facts() -> dict:
    exports = []
    for name in FIXTURES:
        project = load(name)
        for codec in CODECS:
            data = export_contacts(project, codec)
            exports.append({"fixture": name, "codec": codec.value, "sha256": sha(data),
                            "len": len(data), "head": data[:120].hex()})
    tricky = tricky_project()
    for codec in CODECS:
        data = export_contacts(tricky, codec)
        exports.append({"fixture": "tricky", "codec": codec.value, "sha256": sha(data),
                        "len": len(data), "head": data.hex()})
    round_trips = []
    for name in FIXTURES:
        project = load(name)
        parsed = parse_contacts_csv(export_contacts(project, NameCodec.BIG5))
        _, report = append_contacts(project, list(parsed.entries), NameCodec.BIG5)
        round_trips.append({"fixture": name, "entries": len(parsed.entries),
                            "errors": list(parsed.errors), "report": report_facts(report)})
    return {
        "tricky_fields": [f.hex() for f in TRICKY_FIELDS],
        "exports": exports,
        "parse": [{"data": blob(d), "result": parse_result(d)} for d in csv_inputs()],
        "round_trips": round_trips,
    }


