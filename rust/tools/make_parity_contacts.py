def load(name: str) -> Project:
    return f136.load(FIX / name)


def import_case(project: Project, users: list, fmt: NameFormat, codec: NameCodec,
                capacity: int | None = None) -> dict:
    kwargs = {} if capacity is None else {"capacity": capacity}
    try:
        result, report = import_users(project, users, fmt, codec, **kwargs)
    except ValueError as exc:
        return {"error": str(exc)}
    return {"report": report_facts(report), "project": project_summary(result, codec)}


def append_case(project: Project, entries: list[NewContact], codec: NameCodec,
                capacity: int | None = None) -> dict:
    kwargs = {} if capacity is None else {"capacity": capacity}
    try:
        result, report = append_contacts(project, entries, codec, **kwargs)
    except ValueError as exc:
        return {"error": str(exc)}
    return {"report": report_facts(report), "project": project_summary(result, codec)}


