"""Write Python's `big5` and `gbk` codecs as Rust tables (opendrs-core/src/codec_tables.rs).

The WHATWG tables in encoding_rs differ from Python's codecs (ETEN extensions, a few mappings
such as Big5 A145, GB18030 forms), so the name fields are decoded and encoded with Python's own
mapping instead. Run from the repository root:
    python rust/tools/make_codec_tables.py > rust/opendrs-core/src/codec_tables.rs
"""

from __future__ import annotations

import sys
import unicodedata

CODECS = {"big5": "BIG5", "gbk": "GBK"}


def decode_table(codec: str) -> dict[int, str]:
    table: dict[int, str] = {}
    for lead in range(0x81, 0xFF):
        for trail in range(0x40, 0xFF):
            try:
                text = bytes([lead, trail]).decode(codec)
            except UnicodeDecodeError:
                continue
            if len(text) == 1:
                table[lead << 8 | trail] = text
    return table


def single_bytes(codec: str) -> list[int]:
    """High single bytes the codec decodes on their own (none expected)."""
    found = []
    for b in range(0x80, 0x100):
        try:
            if len(bytes([b]).decode(codec)) == 1:
                found.append(b)
        except UnicodeDecodeError:
            pass
    return found


def encode_table(codec: str) -> dict[str, int]:
    table: dict[str, int] = {}
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        try:
            data = ch.encode(codec)
        except UnicodeEncodeError:
            continue
        if len(data) != 2:
            raise SystemExit(f"{codec}: U+{cp:04X} encodes to {data!r}")
        table[ch] = data[0] << 8 | data[1]
    return table


def literal(text: str) -> str:
    out = []
    for ch in text:
        if ch in '"\\' or not ch.isprintable() or ch.isspace() or unicodedata.combining(ch) \
                or unicodedata.category(ch) in ("Cf", "Co", "Cn", "Mn", "Me"):
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def runs(table: dict[int, str]) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    for code in sorted(table):
        if out and out[-1][0] + len(out[-1][1]) == code:
            out[-1] = (out[-1][0], out[-1][1] + table[code])
        else:
            out.append((code, table[code]))
    return out


def emit(codec: str, name: str) -> list[str]:
    decoded = decode_table(codec)
    if single_bytes(codec):
        raise SystemExit(f"{codec}: high single bytes decode: {single_bytes(codec)}")
    encoded = encode_table(codec)
    inverse: dict[str, int] = {}
    for code in sorted(decoded):
        inverse.setdefault(decoded[code], code)
    overrides = sorted((ch, code) for ch, code in encoded.items() if inverse.get(ch) != code)
    decode_only = sorted(ch for ch in inverse if ch not in encoded)
    lines = [f"/// Python's `{codec}`: runs of consecutive two-byte codes and the characters they decode to.",
             f"pub(crate) const {name}_RUNS: &[(u16, &str)] = &["]
    lines += [f"    (0x{code:04X}, {literal(text)})," for code, text in runs(decoded)]
    lines += ["];", "",
              f"/// Characters Python's `{codec}` encodes differently from the first code that decodes to them.",
              f"pub(crate) const {name}_ENCODE: &[(char, u16)] = &["]
    lines += [f"    ('\\u{{{ord(ch):x}}}', 0x{code:04X})," for ch, code in overrides]
    lines += ["];", "", f"/// Characters Python's `{codec}` decodes but cannot encode.",
              f"pub(crate) const {name}_DECODE_ONLY: &[char] = &["]
    lines += [f"    '\\u{{{ord(ch):x}}}'," for ch in decode_only]
    lines += ["];", ""]
    print(f"{codec}: {len(decoded)} codes, {len(overrides)} encode overrides, {len(decode_only)} decode-only",
          file=sys.stderr)
    return lines


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    version = ".".join(map(str, sys.version_info[:3]))
    out = [f"//! Python {version}'s `big5` and `gbk` codecs, generated by `rust/tools/make_codec_tables.py`.",
           "//! Do not edit; regenerate instead.", ""]
    for codec, name in CODECS.items():
        out += emit(codec, name)
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
